_S = None  # range starts / ends / danger set, decoded on first normalize()
_E = None
_GS = None


def _unsupported(what):
    raise NotImplementedError("lypning: unsupported: " + what)


def _refuse(what):
    _unsupported("argument: unicodedata.normalize(" + what + ")")


def _u(cp):
    return "U+%04X" % cp


def _nums(t):
    out = []
    n = sh = 0
    for c in t:
        v = _A.index(c)
        n |= (v & 31) << sh
        if v < 32:
            out.append(n)
            n = sh = 0
        else:
            sh += 5
    return out


def _load():
    global _S, _E, _GS
    _S = []
    _E = []
    cp = 0
    ns = _nums(_R)
    for i in range(0, len(ns), 2):
        cp += ns[i]
        _S.append(cp)
        cp += ns[i + 1]
        _E.append(cp)
        cp += 1
    _GS = set()
    for mi, part in enumerate(_G.split("|")):
        b = 0
        for d in _nums(part):
            b += d
            _GS.add(b * 16 + mi)


def _risky(cp):
    lo = 0
    hi = len(_S)
    while lo < hi:
        mid = (lo + hi) // 2
        if cp < _S[mid]:
            hi = mid
        else:
            lo = mid + 1
    return lo > 0 and cp <= _E[lo - 1]


def _cc(ch):
    i = _M.find(ch)
    return _CC[i] if i >= 0 else "0"


def _pair(b, mi):
    """The composite of base char b and mark index mi, or None."""
    k = b + chr(0x30 + mi)
    i = _D.find(k)
    while i >= 0:
        if not i % 2:
            return chr(0xC0 + i // 2)
        i = _D.find(k, i + 1)
    return None


def _order(buf):
    """Canonical ordering: a stable sort of each non-starter run by class."""
    sw = 0
    for i in range(1, len(buf)):
        c = _cc(buf[i])
        if c == "0":
            continue
        j = i
        while j and _cc(buf[j - 1]) > c:
            buf[j], buf[j - 1] = buf[j - 1], buf[j]
            j -= 1
            sw += 1
    return sw


def _compose(buf):
    res = []
    nc = 0
    st = -1  # index in res of the starter a mark may attach to
    lc = "0"  # class of the last character appended after that starter
    for ch in buf:
        c = _cc(ch)
        if st >= 0 and lc < c:  # not blocked from res[st]
            b = res[st]
            mi = _M.find(ch)
            k = _pair(b, mi)
            if k:
                res[st] = k
                nc += 1
                continue
            if ord(b) * 16 + mi in _GS:
                _refuse(_u(ord(b)) + "+" + _u(ord(ch)))
        if c == "0":
            st = len(res)
            lc = "0"
        else:
            lc = c
        res.append(ch)
    return res, nc


def _flush(buf, nd, pm, nfc, force):
    """Normalise one chunk. Returns (text, input length); text is None when the
    chunk came out byte-identical to its input and the caller can still skip
    building a result string at all."""
    same = True
    if nd or pm:
        sw = _order(buf)
        if nfc:
            # Every one of the nd composites split into exactly one base and
            # one mark, so if nothing was reordered, no mark came from the
            # input, and nd compositions happened, each one went back together.
            buf, nc = _compose(buf)
            same = not sw and not pm and nc == nd
        else:
            same = not sw and not nd
    if same and not force:
        return None, len(buf)
    return "".join(buf), len(buf)


def normalize(form, s):
    if form in ("NFKC", "NFKD"):
        _refuse(form)
    if form not in ("NFC", "NFD"):
        raise ValueError("invalid normalization form")
    # Nothing below U+00C0 has a canonical decomposition, a combining class or
    # a composition, so such a string is already its own NFC and NFD.
    if not s or max(s) < "\xc0":
        return s
    if _S is None:
        _load()
    nfc = form == "NFC"
    res = []  # finished chunks, once there is anything to finish
    buf = []  # the decomposed chunk being built
    nd = pm = 0  # composites split in it; marks it took from the input
    pre = 0  # leading characters of s known to pass through untouched
    chg = False
    # The input is normalised a chunk at a time because a list of 100,000
    # one-character strings exhausts MicroPython's heap, and heap exhaustion in
    # the middle of a file is not a subset boundary anyone can act on. A chunk
    # may end before any STARTER without changing the answer: no non-starter
    # run is split, and the only backwards composition across the seam would be
    # starter + starter, which is Hangul and already refused by _R. While every
    # chunk so far is unchanged nothing is materialised at all, so the ordinary
    # case in the corpus -- NFC over a file that is already NFC -- allocates no
    # output and returns s itself.
    for ch in s:
        cp = ord(ch)
        if 0xC0 <= cp < 0x180:
            i = (cp - 0xC0) * 2
            if _D[i] != " ":
                if len(buf) > 2048:
                    txt, n = _flush(buf, nd, pm, nfc, chg)
                    if txt is None:
                        pre += n
                    else:
                        if not chg:
                            res.append(s[:pre])
                            chg = True
                        res.append(txt)
                    buf = []
                    nd = pm = 0
                buf.append(_D[i])
                buf.append(_M[ord(_D[i + 1]) - 0x30])
                nd += 1
                continue
        elif cp >= _S[0] and _risky(cp):
            _refuse(_u(cp))
        elif cp > 0x2FF and _M.find(ch) >= 0:
            buf.append(ch)
            pm += 1
            continue
        if len(buf) > 2048:
            txt, n = _flush(buf, nd, pm, nfc, chg)
            if txt is None:
                pre += n
            else:
                if not chg:
                    res.append(s[:pre])
                    chg = True
                res.append(txt)
            buf = []
            nd = pm = 0
        buf.append(ch)
    txt, n = _flush(buf, nd, pm, nfc, chg)
    if txt is None and not chg:
        return s
    if not chg:
        res.append(s[:pre])
    res.append(txt)
    return "".join(res)


def is_normalized(form, s):
    return normalize(form, s) == s


