# lypning-mp frozen shim: unicodedata — NFC/NFD over ONE bounded repertoire, and a
# loud refusal for everything else. See micropython/lib/README.md.
#
# The repertoire is the 161 precomposed letters of Latin-1 Supplement + Latin
# Extended-A (U+00C0..U+017F) and the 13 combining marks they decompose to.
# That is what the corpus asks for: every observed import of this module
# compares text that differs only by the composition of a West/North European
# name — Dalén, Åkesson, Öberg — where composed é and decomposed e + U+0301
# must compare equal.
#
# CPython's UCD is hundreds of KB and the whole binary must fit 700,000 B, so
# what is not carried is REFUSED, never passed through as if normalisation had
# succeeded:
#
#   _R  every code point in Unicode 14.0 that NFC/NFD would touch and this
#       file cannot handle — canonical decompositions, non-zero combining
#       classes, second elements of composition pairs, Hangul syllables and
#       jamo — as 409 ranges. Any of them exits 90.
#   _G  every (starter, one of our marks) pair that composes in full Unicode
#       to a character outside the repertoire (K + U+0301 -> U+1E30, and 356
#       more). Attempting one exits 90.
#
# A character with no canonical decomposition, no combining class and no
# composition is unaffected by NFC/NFD — all of ASCII, all of CJK, most of the
# BMP — so passing it through is the identity CPython computes, not an
# approximation. Compatibility decompositions do not affect NFC/NFD either, so
# U+FF21, U+0149 and U+017F are correctly left alone; NFKC/NFKD themselves are
# refused by name. So are category/name/lookup/decimal/digit/numeric/
# combining/east_asian_width/bidirectional/mirrored/decomposition — a guessed
# category table is exactly the silently-wrong answer this contract exists to
# prevent.
#
# The tables were generated by running CPython 3.11.15's unicodedata over every
# code point (decomposition/combining/normalize), never hand-typed, and then
# diffed straight back against it: every one of the 1,112,064 code points on
# its own, every character below U+2000 followed by each of the 13 marks, every
# base with two marks, randomised strings, both forms, both directions,
# idempotence and the cross-form identities. 2,492,872 comparisons, 87,890
# refusals, 0 divergences -- and the same diff over the built binary rather
# than this source, because a shim that agrees with CPython under CPython
# proves nothing about MicroPython.

unidata_version = "14.0.0"  # the UCD the tables were generated from

# The 13 marks, and their canonical combining class as a RANK ("1" < "2"),
# which is all the ordering algorithm compares. 202 = attached below, 230 =
# above.
_M = ("\u0300\u0301\u0302\u0303\u0304\u0306\u0307\u0308\u030a\u030b"
      "\u030c\u0327\u0328")
_CC = "2222222222211"

# Canonical decomposition of U+00C0..U+017F, two chars per code point: the
# ASCII base letter and the mark index as chr(0x30 + i). "  " = no canonical
# decomposition (x, /, Ø, Đ, Ł, Œ, ŋ, ĸ, ı and the compatibility-only ones).
# Read forwards for NFD, searched at an even offset for NFC.
